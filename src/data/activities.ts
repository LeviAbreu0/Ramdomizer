const both = ['alone', 'accompanied'] as const;

type ActivityInput = Omit<
  Activity,
  'allowedCompany' | 'transportation' | 'cooldownHours' | 'steps'
> &
  Partial<
    Pick<Activity, 'allowedCompany' | 'transportation' | 'cooldownHours' | 'steps'>
  >;

function activity(input: ActivityInput): Activity {
  return {
    ...input,
    allowedCompany: input.allowedCompany ?? [...both],
    transportation: input.transportation ?? ['none'],
    cooldownHours: input.cooldownHours ?? 72,
    steps: input.steps ?? [],
  };
}

